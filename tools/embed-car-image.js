// Regenerates src/carImageData.js from images/car.png.
//
// Browsers won't let a page read pixels from an image loaded through file://,
// and we need pixel access to cut out the white background and recolor each car.
// Embedding the PNG as a data URI sidesteps that, so index.html works when
// opened directly from disk.
//
// Usage: node tools/embed-car-image.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const png = fs.readFileSync(path.join(root, "images", "car.png"));
const out = `// Generated by tools/embed-car-image.js from images/car.png. Do not edit by hand.
const CAR_IMAGE_DATA = "data:image/png;base64,${png.toString("base64")}";
`;
fs.writeFileSync(path.join(root, "src", "carImageData.js"), out);
console.log(`Wrote src/carImageData.js (${out.length} bytes)`);

